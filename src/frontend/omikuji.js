  // Each category uses a shuffled deck, so its copy is exhausted before repeating.
  // Only the remaining indices and last index stay in memory, never in storage.
  const decks = new Map();
  const lastIndices = new Map();

  function refillDeck(fortune) {
    const deck = fortune.messages.map((_, index) => index);
    for (let index = deck.length - 1; index > 0; index -= 1) {
      const swapIndex = Math.floor(Math.random() * (index + 1));
      [deck[index], deck[swapIndex]] = [deck[swapIndex], deck[index]];
    }
    // Avoid repeating the last message at the boundary between two decks.
    if (deck.length > 1 && deck[deck.length - 1] === lastIndices.get(fortune.id)) {
      [deck[0], deck[deck.length - 1]] = [deck[deck.length - 1], deck[0]];
    }
    decks.set(fortune.id, deck);
    return deck;
  }

  function draw() {
    if (Math.random() < SUPER_RARE_PROBABILITY) {
      return superRareFortune;
    }
    const fortune = fortunes[Math.floor(Math.random() * fortunes.length)];
    let deck = decks.get(fortune.id);
    if (!deck?.length) {
      deck = refillDeck(fortune);
    }
    const index = deck.pop();
    lastIndices.set(fortune.id, index);
    return { id: fortune.id, label: fortune.label, message: fortune.messages[index] };
  }

  window.ComoOmikuji = Object.freeze({
    fortunes: Object.freeze(fortunes),
    superRareFortune,
    superRareProbability: SUPER_RARE_PROBABILITY,
    draw,
  });
